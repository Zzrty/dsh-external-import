/**
 * Point this package's type checking at a DeepSeek Harness checkout.
 *
 * Building and testing need nothing from the harness, but `npm run typecheck`
 * checks this source against the real plugin APIs, and those packages are not
 * published on npm at the version a current harness uses. This writes
 * `tsconfig.workspace.json` (git-ignored) with `paths` into that checkout's
 * built declarations — the same resolution pnpm's workspace links provide
 * inside the harness repository, without needing a symlink privilege.
 *
 *   npm run link-workspace -- ../deepseek-harness
 *
 * The checkout must be built once (`pnpm run build` inside it) so the
 * `lib/types` declarations exist.
 */

import { access, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

/** Package name → path inside a harness checkout. */
const PACKAGES = {
  '@deepseek-ai/cordis': 'vendor/cordis',
  '@deepseek-ai/dsh-agent': 'packages/core/agent',
  '@deepseek-ai/dsh-session': 'packages/core/session',
  '@deepseek-ai/dsh-skill': 'packages/skill/skill',
  '@deepseek-ai/dsh-system-prompt': 'packages/core/system-prompt',
  '@deepseek-ai/dsh-tools': 'packages/core/tools',
}

const requested = process.argv[2]
if (requested === undefined) {
  console.error('usage: npm run link-workspace -- <path to a deepseek-harness checkout>')
  process.exit(2)
}
const base = resolve(process.cwd(), requested)
try {
  await access(join(base, 'vendor', 'cordis', 'lib', 'types', 'index.d.ts'))
} catch {
  console.error(`${base} has no built vendor/cordis types — point this at a deepseek-harness checkout and run its build first (pnpm run build)`)
  process.exit(2)
}

const paths = {}
const missing = []
for (const [name, relativePath] of Object.entries(PACKAGES)) {
  const declaration = join(base, relativePath, 'lib', 'types', 'index.d.ts')
  const relocatable = relative(root, declaration).split(sep).join('/')
  paths[name] = [relocatable.startsWith('.') ? relocatable : `./${relocatable}`]
  await access(declaration).catch(() => missing.push(`${name} (${declaration})`))
}

const config = {
  // Generated by `npm run link-workspace`; do not commit.
  extends: './tsconfig.json',
  compilerOptions: { paths },
}
await writeFile(join(root, 'tsconfig.workspace.json'), `${JSON.stringify(config, undefined, 2)}\n`, 'utf8')
await readFile(join(root, 'tsconfig.json'), 'utf8').catch(() => {
  console.error('tsconfig.json is missing; is this the package root?')
  process.exit(2)
})

console.log(`wrote tsconfig.workspace.json pointing at ${base}`)
if (missing.length > 0) {
  console.error(`missing built declarations for:\n  ${missing.join('\n  ')}\nrun the harness build (pnpm run build) and try again`)
  process.exit(1)
}
console.log('run `npm run typecheck` to check against that checkout')
